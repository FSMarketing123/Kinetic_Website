// Builds js/directory.js: member contact info encrypted so it is only readable
// after a member signs in with their passcode.
//
//   node tools/build-directory.mjs
//
// Reads member-passcodes.csv (NOT committed: Member, Firm, City, Email, Passcode),
// fills in a passcode for anyone missing one (last name + 4 digits), and writes
// the encrypted directory. Re-run it whenever members or emails change.
//
// Scheme (Web Crypto compatible): one random AES-GCM group key encrypts the
// directory; for each member, the group key is wrapped with a key derived from
// their passcode via PBKDF2-SHA256. A correct passcode is the only way to unwrap.

import { readFileSync, writeFileSync } from "node:fs";
import { webcrypto as crypto, randomInt } from "node:crypto";

const CSV = "member-passcodes.csv";
const OUT = "js/directory.js";
const ITERATIONS = 310000;

function parseCsv(text) {
  const rows = [];
  let row = [], cell = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); cell = "";
      if (row.some(Boolean)) rows.push(row);
      row = [];
    } else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows;
  return body.map(r => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}
const csvCell = v => /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;

const b64 = buf => Buffer.from(buf).toString("base64");
const enc = new TextEncoder();

async function kekFor(passcode, salt, name) {
  const base = await crypto.subtle.importKey("raw", enc.encode(passcode.trim().toLowerCase()), "PBKDF2", false, ["deriveKey"]);
  return crypto.subtle.deriveKey(
    { name: "PBKDF2", hash: "SHA-256", salt: enc.encode(`${salt}:${name}`), iterations: ITERATIONS },
    base, { name: "AES-GCM", length: 256 }, false, ["encrypt"]);
}
async function seal(key, bytes) {
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, bytes);
  return { iv: b64(iv), ct: b64(ct) };
}

const members = parseCsv(readFileSync(CSV, "utf8"));
const used = new Set(members.map(m => m.Passcode).filter(Boolean));
for (const m of members) {
  if (m.Passcode) continue;
  const last = m.Member.split(/\s+/).pop().replace(/[^A-Za-z]/g, "");
  do m.Passcode = `${last}${randomInt(1000, 10000)}`; while (used.has(m.Passcode));
  used.add(m.Passcode);
  console.log(`new passcode for ${m.Member}`);
}
const cols = ["Member", "Firm", "City", "Email", "Passcode"];
writeFileSync(CSV, [cols.join(","), ...members.map(m => cols.map(c => csvCell(m[c] || "")).join(","))].join("\n") + "\n");

const salt = b64(crypto.getRandomValues(new Uint8Array(12)));
const groupRaw = crypto.getRandomValues(new Uint8Array(32));
const groupKey = await crypto.subtle.importKey("raw", groupRaw, "AES-GCM", false, ["encrypt"]);
const directory = Object.fromEntries(members.map(m => [m.Member, { email: m.Email.trim().toLowerCase() }]));
const sealedDirectory = await seal(groupKey, enc.encode(JSON.stringify(directory)));
const keyring = {};
for (const m of members) keyring[m.Member] = await seal(await kekFor(m.Passcode, salt, m.Member), groupRaw);

writeFileSync(OUT, `// Generated by tools/build-directory.mjs. Do not edit by hand.
// Member contact info, encrypted. Unlocked in the browser by a member's passcode.
window.KINETIC_DIRECTORY = ${JSON.stringify({ salt, iterations: ITERATIONS, keyring, directory: sealedDirectory }, null, 2)};
`);
console.log(`wrote ${OUT} for ${members.length} members`);
